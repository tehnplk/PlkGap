import { _electron as electron, expect } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdtemp, mkdir, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const directory = await mkdtemp(join(tmpdir(), 'plkgap-ui-test-'))
const env = { ...process.env, PLKGAP_TEST_DATA_DIR: directory }
delete env.ELECTRON_RUN_AS_NODE
let application
try {
  application = await electron.launch({ args: ['.'], env, timeout: 60000 })
  const page = await application.firstWindow({ timeout: 60000 })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.getByRole('status').filter({ hasText: 'Connected' }).waitFor({ timeout: 60000 })
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/plkgap-main-ui.png', fullPage: true })
  const toolbar = page.getByRole('toolbar', { name: 'Main toolbar' })
  await toolbar.getByRole('button', { name: 'Database', exact: true }).click()
  const database = page.getByRole('region', { name: 'Database window' })
  await expect(database).toBeVisible()
  assert.match(await page.locator('main').innerText(), /POINT\(100.2659 16.8211\)/)
  await toolbar.getByRole('button', { name: 'Database', exact: true }).click()
  await expect(database).toHaveCount(1)
  const beforeMove = await database.boundingBox()
  await page.mouse.move(beforeMove.x + 100, beforeMove.y + 18)
  await page.mouse.down()
  await page.mouse.move(beforeMove.x + 170, beforeMove.y + 38, { steps: 8 })
  await page.mouse.up()
  const afterMove = await database.boundingBox()
  assert.ok(afterMove.x > beforeMove.x + 50, 'Child window moves')
  const handle = await database.locator('.resize-handle').boundingBox()
  await page.mouse.move(handle.x + 12, handle.y + 12)
  await page.mouse.down()
  await page.mouse.move(handle.x + 72, handle.y + 12, { steps: 8 })
  await page.mouse.up()
  assert.ok((await database.boundingBox()).width > afterMove.width + 40, 'Child window resizes')
  await database.getByRole('button', { name: 'Maximize Database' }).click()
  await expect(database).toHaveClass(/maximized/)
  await database.getByRole('button', { name: 'Restore Database' }).click()
  await database.getByRole('button', { name: 'Minimize Database' }).click()
  await expect(database).toHaveCount(0)
  await page.locator('.window-dock').getByRole('button', { name: 'Database', exact: true }).click()
  await expect(database).toBeVisible()
  await toolbar.getByRole('button', { name: 'Welcome', exact: true }).click()
  await toolbar.getByRole('button', { name: 'Tile', exact: true }).click()
  const welcome = page.getByRole('region', { name: 'Welcome window' })
  const tiledDb = await database.boundingBox()
  const tiledWelcome = await welcome.boundingBox()
  assert.ok(tiledDb.x + tiledDb.width <= tiledWelcome.x, 'Tiled windows do not overlap')
  await page.screenshot({ path: 'artifacts/plkgap-mdi-windows.png', fullPage: true })
  await toolbar.getByRole('button', { name: 'Cascade', exact: true }).click()
  const cascadeDb = await database.boundingBox()
  const cascadeWelcome = await welcome.boundingBox()
  assert.ok(cascadeWelcome.x > cascadeDb.x && cascadeWelcome.x < cascadeDb.x + cascadeDb.width)
  await page.getByRole('menuitem', { name: 'View', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Toolbar', exact: false }).click()
  await expect(toolbar).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'View', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Toolbar', exact: false }).click()
  await expect(toolbar).toBeVisible()
  await page.getByRole('menuitem', { name: 'Help', exact: true }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'About PlkGap' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('region', { name: 'About PlkGap window' })).toBeVisible()
  await page.getByRole('menuitem', { name: 'Window', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Close all windows' }).click()
  await expect(page.locator('.child-window')).toHaveCount(0)
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(640, 480))
  await toolbar.getByRole('button', { name: 'Database', exact: true }).click()
  await expect(database).toBeVisible()
  const workspaceBox = await page.locator('.workspace').boundingBox()
  const smallDb = await database.boundingBox()
  assert.ok(smallDb.x >= workspaceBox.x && smallDb.x + smallDb.width <= workspaceBox.x + workspaceBox.width + 1)
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false)
  await page.screenshot({ path: 'artifacts/plkgap-small-window.png', fullPage: true })
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined')
  await mkdir('artifacts', { recursive: true })
  await page.screenshot({ path: 'artifacts/plkgap-desktop.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: Electron MDI menus, toolbar, move/resize, minimize/restore, tile/cascade, keyboard menu, small viewport and PostGIS status')
} finally {
  if (application) await application.close()
  await rm(directory, { recursive: true, force: true })
}
